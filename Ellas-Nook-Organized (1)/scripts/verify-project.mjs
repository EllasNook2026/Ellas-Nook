import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const root = process.cwd();
const read = p => fs.readFileSync(path.join(root,p),'utf8');
const mustExist = ['public/index.html','public/studio/dashboard.html','public/studio/studio.js','public/studio/studio.css','public/studio/config.js','src/index.js','schema.sql','wrangler.toml','scripts/hash-password.mjs'];
for (const p of mustExist) assert.ok(fs.existsSync(path.join(root,p)), `Missing required file: ${p}`);
assert.equal(fs.existsSync(path.join(root,'studio')), false, 'Duplicate root studio/ must not exist');
assert.equal(fs.existsSync(path.join(root,'public/studio/setup.sql')), false, 'SQL should not be served as a public asset');
const wrangler=read('wrangler.toml');
assert.match(wrangler,/directory\s*=\s*"\.\/public"/);
assert.match(wrangler,/database_id\s*=\s*"9fb6c77c-93c1-4380-b663-6a5c1f91dd11"/);
assert.doesNotMatch(wrangler,/REPLACE_WITH|YOUR_DATABASE_ID/);
assert.match(wrangler,/binding\s*=\s*"ASSETS"/);
assert.match(wrangler,/binding\s*=\s*"DB"/);
assert.match(wrangler,/binding\s*=\s*"MEDIA"/);
assert.match(read('public/studio/config.js'),/apiBase:\s*'\/api'/);
assert.match(read('public/index.html'),/const API='\/api'/);
assert.match(read('src/index.js'),/url\.pathname\.startsWith\('\/api\/'\)/);
assert.match(read('src/index.js'),/env\.ASSETS\.fetch\(request\)/);
assert.match(read('README-CLOUDFLARE.md'),/Do not deploy this project through GitHub Pages/);
const deployable = ['public/index.html','public/studio/dashboard.html','public/studio/studio.js','public/studio/config.js','public/studio/README.md'];
for (const p of deployable) assert.doesNotMatch(read(p),/https:\/\/[^\s'"`]*supabase\.co|REPLACE_WITH_D1_DATABASE_ID/i, `Stale backend reference in ${p}`);
const html=read('public/index.html');
for (const n of Array.from(html.matchAll(/(?:src|href)="(assets\/[^"?#]+)"/g),m=>m[1])) assert.ok(fs.existsSync(path.join(root,'public',n)),`Broken asset reference ${n}`);
console.log('Ella’s Nook project structure/configuration checks passed.');
